#!/usr/bin/env python3
"""Prepare game models without overwriting existing OBJ files."""
from pathlib import Path
from math import sin, cos, pi, sqrt

MODELS = Path(__file__).resolve().parents[1] / 'OpenGLrememberProj/models'


def write_model(name, faces):
    path = MODELS / name
    if path.exists():
        return
    lines = ['# Generated by scripts/prepare_models.py.']
    index = 1
    for points in faces:
        a, b, c = points[:3]
        u = [b[i] - a[i] for i in range(3)]
        v = [c[i] - a[i] for i in range(3)]
        n = [u[1]*v[2]-u[2]*v[1], u[2]*v[0]-u[0]*v[2], u[0]*v[1]-u[1]*v[0]]
        length = sqrt(sum(x*x for x in n)) or 1
        for j, point in enumerate(points):
            lines.append('v ' + ' '.join(f'{x:.6f}' for x in point))
            lines.append('vt ' + ('0 0', '1 0', '1 1', '0 1')[j % 4])
            lines.append('vn ' + ' '.join(f'{x/length:.6f}' for x in n))
        lines.append('f ' + ' '.join(f'{i}/{i}/{i}' for i in range(index, index+len(points))))
        index += len(points)
    path.write_text('\n'.join(lines) + '\n', encoding='ascii')
    print(f'Создана модель: OpenGLrememberProj/models/{path.name}')


def prepare():
    # A triangular glider, within the original player's 6 x 2 collision box.
    top = [(-3, -1, 0.4), (3, 0, 0.4), (-3, 1, 0.4)]
    bottom = [(x, y, -0.4) for x, y, z in top]
    faces = [top, list(reversed(bottom))]
    for i in range(3):
        j = (i+1) % 3
        faces.append([bottom[i], bottom[j], top[j], top[i]])
    write_model('Drossel.obj', faces)
    write_model('background.obj', [[(-38, -19, 0), (38, -19, 0), (38, 19, 0), (-38, 19, 0)]])
    faces = []
    def sphere(lat, lon):
        return (0.9*cos(lat)*cos(lon), 0.9*cos(lat)*sin(lon), 0.9*sin(lat))
    for row in range(12):
        a, b = -pi/2 + row*pi/12, -pi/2 + (row+1)*pi/12
        for col in range(24):
            c, d = col*2*pi/24, (col+1)*2*pi/24
            quad = [sphere(a, c), sphere(a, d), sphere(b, d), sphere(b, c)]
            faces.append(quad[1:] if row == 0 else quad[:3] if row == 11 else quad)
    write_model('ball.obj', faces)


if __name__ == '__main__':
    prepare()
